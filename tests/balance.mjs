// Seeded simulations use the shipping combat, item, reward and upgrade functions.
import {writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {freshState} from '../js/save.js';
import {CONFIG as C,INITIAL_IDS} from '../js/config.js';
import {buy,cost} from '../js/upgrades.js';
import {encounter,clone,seedRandom,milestone} from './helpers.js';
function spend(s,build='balanced'){let count=0;for(let i=0;i<10000;i++){const key=build==='attack-only'?'attack':INITIAL_IDS.toSorted((a,b)=>cost(s,a).log-cost(s,b).log)[0];if(!buy(s,key,1))break;count++;}return count;}
function canWin(s,id,rng){const trial=clone(s);return encounter(trial,id,'progress',false,rng);}
function campaign(seed,goal=380,budget=20000,focus=null,build='balanced'){
  const s=freshState(),rng=seedRandom(seed),available=focus?[focus]:INITIAL_IDS;let farms=0,wins=0,losses=0,actions=0,buys=spend(s,build),stalled=false;
  for(let n=0;n<budget&&Math.min(...available.map(id=>s.bosses[id].highest))<goal;n++){
    const ids=available.toSorted((a,b)=>s.bosses[a].highest-s.bosses[b].highest);
    let chosen=null;
    for(const id of ids){const f=canWin(s,id,()=>.5);if(f.won){chosen=id;break;}}
    if(chosen){const f=encounter(s,chosen,'progress',false,rng);actions+=f.turn;if(f.won)wins++;else losses++;}
    else{
      const candidates=available.filter(id=>s.bosses[id].highest>0).map(id=>({id,f:encounter(clone(s),id,'repeat',false,()=>.5)})).filter(x=>x.f.won).sort((a,b)=>b.f.reward.log-a.f.reward.log);
      if(!candidates.length){stalled=true;break;}
      const f=encounter(s,candidates[0].id,'repeat',false,rng);actions+=f.turn;if(f.won)farms++;else losses++;
    }
    buys+=spend(s,build);
  }
  return {s,result:{seed,focus,build,levels:Object.fromEntries(INITIAL_IDS.map(id=>[id,s.bosses[id].highest])),wins,farms,losses,actions,buys,stalled}};
}
// Threshold search measures the player upgrades required to win an actual encounter.
function requiredUpgrades(id,level,seed){
  let lo=0,hi=20000;
  while(lo<hi){const mid=Math.floor((lo+hi)/2),s=freshState();s.bosses[id].unlocked=true;milestone(s,id,level-1);s.items={};s.levels={attack:mid,health:mid,defense:mid};
    const f=encounter(s,id,'progress',false,seedRandom(seed));if(f.won)hi=mid;else lo=mid+1;}
  return lo;
}
const runs=[11,22,33].map(seed=>campaign(seed));
console.log('Campaigns',JSON.stringify(runs.map(r=>r.result)));
assert.ok(runs.every(r=>!r.result.stalled&&Math.min(...Object.values(r.result.levels))>=380),'Initial campaign stalls');
const focused=campaign(44,100,10000,'attack');
console.log('Focused',JSON.stringify(focused.result));
assert.ok(focused.result.farms>0&&!focused.result.stalled&&focused.result.levels.attack>=100,'Repetition must support a focused campaign');
const offensive=campaign(55,100,10000,null,'attack-only');
const balanced100=campaign(55,100);
const thresholds=Object.fromEntries(['attack','defense','health','critical','penetration','vampirism'].map(id=>[id,[1,2,10].map(n=>({level:n,upgrades:requiredUpgrades(id,n,777)}))]));
assert.ok(thresholds.critical[0].upgrades>thresholds.attack[0].upgrades+50);
assert.ok(thresholds.penetration[0].upgrades>thresholds.critical[0].upgrades);
assert.ok(thresholds.vampirism[0].upgrades>thresholds.penetration[0].upgrades);
const increments=Object.fromEntries(Object.entries(thresholds).map(([id,t])=>[id,t[2].upgrades-t[0].upgrades]));
assert.ok(increments.critical>increments.attack*2);assert.ok(increments.penetration>increments.critical*2);assert.ok(increments.vampirism>increments.penetration*2);
const anchors=['critical','penetration','vampirism'].map(id=>({id,anchor:C.bosses[id].anchor,advanced:requiredUpgrades(id,1,777),initial:requiredUpgrades('attack',C.bosses[id].anchor,777)}));
// Equal frozen character: no purchases, but actual earned relics are included.
const frozen=Object.fromEntries(Object.keys(C.bosses).map(id=>{const s=freshState();s.bosses[id].unlocked=true;s.levels={attack:1000,health:1000,defense:1000};let wins=0;for(let n=0;n<2000;n++){if(!encounter(s,id,'progress',false,seedRandom(n+1)).won)break;wins++;}return [id,wins];}));
assert.ok(frozen.attack>frozen.critical*2&&frozen.critical>frozen.penetration*2&&frozen.penetration>frozen.vampirism*2);
// Budget generated by a real repeat encounter buys an upgrade and can close a wall.
const variance=['critical','penetration','vampirism'].map(id=>({id,upgradesAcrossSeeds:[1,2,3,4,5].map(seed=>requiredUpgrades(id,1,seed))}));
const advancedEconomy=['critical','penetration','vampirism'].map(id=>{
  const s=clone(runs[0].s);let victories=0,actions=0;
  for(let i=0;i<250;i++){const f=encounter(s,id,'progress',false,seedRandom(i+10));actions+=f.turn;if(!f.won)break;victories++;spend(s);}
  return {id,victories,actions,endedAtWall:victories<250};
});
assert.ok(advancedEconomy.every(r=>r.endedAtWall),'Advanced gold loop runs away');
const output={campaigns:runs.map(r=>r.result),focused:focused.result,balanced100:balanced100.result,offensive:offensive.result,advancedEconomy,thresholds,increments,anchors,frozen,variance,notes:['Seeded fights, real costs and drops. Conservative scouting previews fights without spending gold.','Threshold benchmarks isolate encounter difficulty; levels are generated fixtures, not reachable campaign saves.','Long-term thresholds, critical variance and build specialization still need player telemetry.']};
await writeFile('tests/balance-results.json',JSON.stringify(output,null,2));
console.log(JSON.stringify(output,null,2));
